/**
 * Shim for next/config — removed in Next.js 16.
 * @storybook/nextjs v8 calls require.resolve('next/config') at preset-load
 * time (before webpack runs), so a webpack alias is insufficient.
 * This script writes a minimal shim into node_modules/next/config.js so
 * Storybook can find the module. It is run automatically via the
 * `postinstall` npm script after every `npm install`.
 */

import { writeFileSync } from 'fs'
import { resolve } from 'path'
import { fileURLToPath } from 'url'

const root = resolve(fileURLToPath(import.meta.url), '../../')
const dest = resolve(root, 'node_modules/next/config.js')

const shim = `// Auto-generated by scripts/shim-next-config.mjs
// next/config was removed in Next.js 16; this shim satisfies @storybook/nextjs v8.
'use strict'
let _config = {}
module.exports = function getConfig() { return _config }
module.exports.default = module.exports
module.exports.setConfig = function setConfig(cfg) { _config = cfg }
`

writeFileSync(dest, shim, 'utf8')
console.log('✓ next/config shim written to node_modules/next/config.js')
